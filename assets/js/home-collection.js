(function () {
  'use strict';
  const section = document.querySelector('.home-editorial-collection');
  if (!section) return;
  const buttons = Array.from(section.querySelectorAll('[data-hec-select]'));
  const panels = Array.from(section.querySelectorAll('.hec-feature'));
  const showcase = section.querySelector('.hec-showcase');
  const status = section.querySelector('.hec-status');
  if (!showcase || !buttons.length || panels.length !== buttons.length) return;
  section.querySelector('.hec-switcher').hidden = false;

  function select(button) {
    if (button.getAttribute('aria-pressed') === 'true') return;
    const id = button.getAttribute('aria-controls');
    panels.forEach(panel => { panel.hidden = panel.id !== id; });
    buttons.forEach(item => item.setAttribute('aria-pressed', String(item === button)));
    status.textContent = section.querySelector('#' + id + ' h3').textContent;
  }

  function selectRelative(step) {
    const current = buttons.findIndex(button => button.getAttribute('aria-pressed') === 'true');
    const next = (current + step + buttons.length) % buttons.length;
    select(buttons[next]);
  }

  buttons.forEach((button, index) => {
    button.addEventListener('click', () => select(button));
    button.addEventListener('keydown', event => {
      let next;
      if (event.key === 'ArrowRight') next = (index + 1) % buttons.length;
      if (event.key === 'ArrowLeft') next = (index - 1 + buttons.length) % buttons.length;
      if (event.key === 'Home') next = 0;
      if (event.key === 'End') next = buttons.length - 1;
      if (next === undefined) return;
      event.preventDefault();
      buttons[next].focus();
      select(buttons[next]);
    });
  });

  // On touch-first devices, the featured product doubles as a horizontal
  // carousel. Vertical intent is left to the page, while a completed swipe
  // changes exactly one model and suppresses the link click generated by touch.
  const touchDevice = window.matchMedia('(any-pointer: coarse)');
  let start = null;
  let suppressClick = false;
  let clickTimer;

  showcase.addEventListener('touchstart', event => {
    if (!touchDevice.matches || event.touches.length !== 1) {
      start = null;
      return;
    }
    const touch = event.touches[0];
    start = { x: touch.clientX, y: touch.clientY, time: Date.now() };
  }, { passive: true });

  showcase.addEventListener('touchend', event => {
    if (!start || !touchDevice.matches || event.changedTouches.length !== 1) {
      start = null;
      return;
    }
    const touch = event.changedTouches[0];
    const deltaX = touch.clientX - start.x;
    const deltaY = touch.clientY - start.y;
    const elapsed = Date.now() - start.time;
    start = null;

    if (elapsed > 800 || Math.abs(deltaX) < 44 || Math.abs(deltaX) <= Math.abs(deltaY) * 1.25) return;

    selectRelative(deltaX < 0 ? 1 : -1);
    suppressClick = true;
    window.clearTimeout(clickTimer);
    clickTimer = window.setTimeout(() => { suppressClick = false; }, 450);
  }, { passive: true });

  showcase.addEventListener('touchcancel', () => { start = null; }, { passive: true });
  showcase.addEventListener('click', event => {
    if (!suppressClick) return;
    event.preventDefault();
    event.stopPropagation();
    suppressClick = false;
  }, true);
})();
